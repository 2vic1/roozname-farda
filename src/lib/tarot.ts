export const FULL_DECK: TarotCard[] = [
  ...MAJOR.map(([name, sym, kw], i): TarotCard => ({
    id: `M${i}`,
    arcana: 'major',
    name: `${name} (${i})`,
    sym,
    kw,
    rank: String(i),
  })),
  ...SUITS.flatMap((s) =>
    RANKS.map((r): TarotCard => ({
      id: `${s.key}-${r.fa}`,
      arcana: s.key,
      name: `${r.fa} ${s.fa}`,
      sym: s.emoji,
      kw: [...r.ess, ...s.domain.slice(0, 2)],
      rank: r.fa,
    })),
  ),
]

// ── چیدمان‌ها ──
export const SPREADS = {
  single: {
    fa: 'کارت روزانه',
    positions: ['پیام امروز تو'],
  },
  three: {
    fa: 'گذشته · حال · آینده',
    positions: ['گذشته/ریشهٔ ماجرا', 'اکنون/وضعیت تو', 'آیندهٔ نزدیک/مسیر پیش‌رو'],
  },
  five: {
    fa: 'صلیب پنج‌کارته',
    positions: ['هستهٔ ماجرا', 'نیروی موافق', 'نیروی مخالف', 'آنچه پنهان مانده', 'توصیهٔ نهایی'],
  },
} as const

export type SpreadKey = keyof typeof SPREADS

export function isSpreadKey(v: unknown): v is SpreadKey {
  return v === 'single' || v === 'three' || v === 'five'
}

export interface DrawnCard {
  name: string
  sym: string
  arcana: TarotCard['arcana']
  arcanaFa: string
  reversed: boolean
  kw: string[]
  position: string
}

const ARCANA_FA: Record<TarotCard['arcana'], string> = {
  major: 'نیای بزرگ',
  wands: 'چوبدست · آتش',
  cups: 'جام · آب',
  swords: 'شمشیر · هوا',
  pentacles: 'سکه · خاک',
}

/** قرعه با random رمزنگاهی — بدون تکرار کارت + معکوس با احتمال ~۴۵٪ */
export function drawCards(spread: SpreadKey): DrawnCard[] {
  const n = SPREADS[spread].positions.length
  const pool = FULL_DECK.map((_, i) => i)
  const picked: number[] = []
  for (let k = 0; k < n; k++) {
    const idx = randomInt(0, pool.length)
    picked.push(pool[idx])
    pool.splice(idx, 1)
  }
  return picked.map((cardIdx, i) => {
    const c = FULL_DECK[cardIdx]
    return {
      name: c.name,
      sym: c.sym,
      arcana: c.arcana,
      arcanaFa: ARCANA_FA[c.arcana],
      reversed: randomInt(100) < 45,
      kw: c.kw,
      position: SPREADS[spread].positions[i],
    }
  })
}

/** پرامپت تفسیر حرفه‌ای — خروجی ساختاریافته با ◆ */
export function buildPrompt(cards: DrawnCard[], question: string, spreadFa: string) {
  const cardLines = cards
    .map(
      (c, i) =>
        `کارت ${i + 1} — جایگاه «${c.position}»: ${c.name} (${c.arcanaFa}) — ${
          c.reversed ? 'معکوس' : 'مستقیم'
        } — کلیدواژه‌ها: ${c.kw.join('، ')}`,
    )
    .join('\n')

  const q = question.trim()
    ? `سؤال درخواست‌کننده (مهم — تفسیر را حول همین بچرخان): «${question.trim()}»`
    : `سؤالی داده نشده — تفسیر عمومیِ هوشمندانه برای مسیر روزها و فضای کلی زندگی درخواست‌کننده بده.`

  return {
    system: `تو «تاروت‌خوانِ حرفه‌ای» با ۳۰ سال تجربه‌ای؛ روان‌شناسی نمادها، افسانه‌شناسی و کابالا را خوب می‌دانی. سبک تو: عمیق، شفاف، محترمانه و بی‌تعارف — نه کلیشه‌ای، نه ترسناک. هیچ‌وقت مرگ/بلا را حتمی اعلام نمی‌کنی؛ کارت‌ها را «زبان نماد برای تأمل» می‌خوانی. همیشه فقط فارسی روان بنویس.

ساختار اجباری پاسخ — بخش‌ها دقیقاً با این نشان‌ها شروع شوند:
◆ نگاه کلی — دو تا سه جمله دربارهٔ فضای کل چیدمان و ربطش به سؤال.
◆ تفسیر کارت‌ها — برای هر کارت یک بلوک: خط اول «— نام کارت (جایگاه — مستقیم/معکوس):» بعد ۴ تا ۶ جمله تفسیر واقعی و دقیق (معنی اصلی کارت + حالت معکوس در صورت معکوس بودن + ربط به جایگاه و سؤال + یک اشارهٔ نمادین/افسانه‌ای که عمق بدهد).
◆ داستانِ ترکیبی — کارت‌ها کنار هم چه روایتی می‌سازند؛ اتصال‌ها و تضادها را صدا بزن؛ اگر کارت‌های هم‌خال یا هم‌شماره الگویی هست بگو.
◆ توصیهٔ عملی — سه کار عملی مشخص که همین هفته می‌شود کرد.
◆ زمان‌بندی — بر اساس ماهیت کارت‌ها (آتش سریع، خاک کند...) بگو کی ماجرا گره می‌خورد/رونق می‌گیرد.
◆ پیام پایانی — یک جملهٔ ماندگار، مثل شعار شخصی.

قواعد: مطلق‌سازی نکن («شاید»، «نشانه‌ها می‌گویند»)؛ از ادبیات پیشگویی قطعی پرهیز کن؛ اگر کارت تاریک است، همیشه یک در خروجی هم نشان بده. حداقل ۷۰۰ و حداکثر ۱۲۰۰ کلمه. پایان پاسخ همیشه این جمله باشد: «تاروت آینهٔ تأمل است، نه تقدیرِ قطعی — تصمیم نهایی با توست.»`,
    user: `چیدمان: ${spreadFa}
${q}

کارت‌های افتاده:
${cardLines}`,
  }
}

